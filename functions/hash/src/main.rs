//! `hash`: the sha256 (or sha512) of whatever was piped in, as hex.
//!
//! The least glamorous tool in the catalog and the one agents reach for
//! constantly: a stable key for a document, an idempotency token for an
//! action, a way to tell two versions of a file apart, a checksum to compare
//! against one somebody published.
//!
//! It exists here rather than in the agent because the bytes are already on
//! the peer — a fetched page, a converted table — and shipping a megabyte
//! back to the caller to hash it there is the round trip this lane is
//! supposed to remove.
//!
//! Implemented from the FIPS 180-4 pseudocode, in one file, with the
//! standard vectors as tests: a dependency-free module is one a provider can
//! read in an afternoon before agreeing to run it.
//!
//! stdin: any bytes. args: `sha256` (default) or `sha512`. stdout: lowercase
//! hex and a newline.

use std::io::{Read, Write};

fn main() {
    let which = std::env::args().nth(1).unwrap_or_else(|| "sha256".into());
    let mut data = Vec::new();
    if std::io::stdin().read_to_end(&mut data).is_err() {
        let _ = writeln!(std::io::stderr(), "could not read stdin");
        std::process::exit(2);
    }
    let digest = match which.as_str() {
        "sha256" => hex(&sha256(&data)),
        "sha512" => hex(&sha512(&data)),
        other => {
            let _ = writeln!(std::io::stderr(), "unknown algorithm {other:?} (sha256, sha512)");
            std::process::exit(2);
        }
    };
    let mut out = std::io::stdout();
    let _ = writeln!(out, "{digest}");
    let _ = out.flush();
}

pub fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

